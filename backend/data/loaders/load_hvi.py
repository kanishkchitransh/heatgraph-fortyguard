def load_hvi():
    init_db()
    db = SessionLocal()
    count = 0
    skipped = 0

    try:
        with open(DATA_FILE, newline="", encoding="utf-8-sig") as f:
            reader = csv.DictReader(f)
            # Figure out actual column names
            for row in reader:
                # Columns: "ZIP Code Tabulation Area (ZCTA) 2020", "Heat Vulnerability Index (HVI)"
                zip_col = next((k for k in row if "zip" in k.lower() or "zcta" in k.lower()), None)
                hvi_col = next((k for k in row if "hvi" in k.lower() or "vulnerability" in k.lower()), None)
                if not zip_col or not hvi_col:
                    break

                zip_code = row[zip_col].strip().zfill(5)
                hvi_raw  = row[hvi_col].strip()
                try:
                    hvi_rank = int(float(hvi_raw))
                except ValueError:
                    skipped += 1
                    continue

                centroid = ZIP_CENTROIDS.get(zip_code)
                if not centroid:
                    skipped += 1
                    continue
                lat, lon = centroid

                entity_id = f"hvi-{zip_code}"
                db.merge(Entity(
                    id=entity_id,
                    name=f"HVI Zone — ZIP {zip_code} (rank {hvi_rank}/5)",
                    entity_type="hvi_zone",
                    role="receptor",
                    city="nyc",
                    lat=lat,
                    lon=lon,
                    address=f"ZIP {zip_code}, NYC",
                    extra_json=json.dumps({
                        "zip_code":   zip_code,
                        "hvi_rank":   hvi_rank,
                        # HVI rank 5 = most vulnerable: high poverty, low green, hot surface
                        "is_high_risk": hvi_rank >= 4,
                    }),
                ))
                count += 1

        db.commit()
        print(f"HVI: loaded {count} receptor nodes (skipped {skipped} — no centroid)")
    finally:
        db.close()

if __name__ == "__main__":
    load_hvi()
